package com.codeloom.domain.port;

/**
 * 一条命令是**怎么结束的**。
 *
 * <h2>为什么它必须是一个事实，而不是"有没有抛出异常"</h2>
 * "超时"和"被取消"不能靠抛异常表达 —— 抛异常**会把结果一起扔掉**：
 * 一条跑了三分钟的构建被超时杀掉时，它已经打出来的那些行正是模型最想看的东西
 * （它跑到哪一步卡住的），而抛异常等于说"什么都没有"。
 *
 * <p>所以这两种终止现在是**返回值**：进程确实结束了，只是不是它自己结束的。
 * 真正拿不到结果的只剩"起不来"和"等待的线程被中断"——那两种仍然抛异常。
 *
 * <h2>为什么它值得进 domain</h2>
 * 因为有两个消费方，而它们要的**不是同一件事**：
 * <ul>
 *   <li>{@code RunCommandTool} 要把它说成"超时了，这次调用失败了"；</li>
 *   <li>{@code VerificationRunner} 要把它说成"**这次没验成**"，并且必须和
 *       "验证未通过"分开 —— 混成后者的话，模型会去修一个根本不存在的问题。</li>
 * </ul>
 * 一个事实、两种说法。所以事实放在这里，措辞留给各自的消费方 ——
 * 这个类型里没有一个字是给人看的。
 */
public enum CommandTermination {

    /** 进程自己跑完了。退出码是多少，由调用方按各自命令的语义解释。 */
    COMPLETED,

    /** 超过时限，进程树已被我们强杀。**它可能已经改过文件。** */
    TIMED_OUT,

    /** 用户取消了（按 Esc），进程树已被我们强杀。同上，它可能已经改过文件。 */
    CANCELLED
}
