package com.codeloom.domain.port;

import com.codeloom.domain.project.ProjectId;
import com.codeloom.domain.session.SessionId;
import com.codeloom.domain.user.UserId;

/**
 * 把一条会话的事件流**抹掉** —— 全项目唯一一处 DELETE 事件的地方。
 *
 * <h2>为什么不直接给 {@link EventStore} 加一个 delete 方法</h2>
 * 因为那个接口的类注释写着「append-only，永不修改、永不删除」，而那句话**服务的是
 * 回放、断线补齐、崩溃恢复**三件事 —— 它们全都建立在"已经写下的行不会再变"上面。
 * 把 delete 挂在同一个接口上，那句承诺就变成了半真半假的话，而且没有任何东西会提醒你。
 *
 * <p>单开一个端口，这个例外就有了一个**能被 grep 到的名字**。名字本身就是它的说明：
 * 只有"用户主动丢弃一条会话"能走到这里，别的任何路径都不该碰它。
 *
 * <h2>为什么这件事本身是正当的，而不是对 append-only 的破坏</h2>
 * 那条规则要保护的三件事，对被丢弃的会话**一件都不适用**：
 * 没有人会回放一条被丢掉的对话、没有一轮会崩溃在它上面需要恢复、
 * 而"谁改了代码"这个审计问题的答案在 **git log**（提交署名）里，不在事件流里。
 *
 * <p>反过来，留着它是有代价的：用户明确说了不要，而它还会一直占着库、
 * 出现在任何一次全表扫描里。
 *
 * <h2>它删什么、不删什么</h2>
 * 只删**这条会话的事件**。别的会话的事件、聊天记录、项目、以及**工作区**都不在它的范围里 ——
 * 工作区属于「人 + 项目」而不是某条会话，那正是"丢弃对话但代码留着"能成立的原因。
 */
public interface EventDiscard {

    /**
     * 删掉这条会话的全部事件。
     *
     * <p><strong>调用方必须先确认这条会话没有在跑</strong>（持有它的树锁）——
     * 一边删、一边有一轮在往里写，会得到一个谁也说不清的结果。那道检查在应用层，
     * 见 {@code SessionService.discard}。
     */
    void bySession(SessionId sessionId);

    /**
     * 删掉**这个人在这个项目里**所有会话的事件 —— 「退出项目」的一步。
     *
     * <h2>为什么它和"逐个会话删"不是同一件事</h2>
     * 逐个删要先把会话都查出来、再一条条走一遍，而这两件事在这里都不该发生：
     * 那些会话**马上就要一起消失了**，它们只是"要清掉的东西"里的一类，没有独立的意义。
     * 更重要的是——逐个删会在一个已经删掉一半的项目上留下可观察的中间态，
     * 而这里所有删除在同一个事务里。
     *
     * <p>上一条 {@link #bySession} 的正文（为什么这件事正当、为什么它不删工作区）
     * 在这里同样成立，差别只有范围。
     *
     * <p><strong>它同时覆盖"最后一个人退出"那条路。</strong>那时候这个人就是项目里
     * 唯一剩下的成员，所以"他的会话"和"这个项目的会话"是同一批 ——
     * 不需要再来一个按项目删的方法。
     *
     * <p><strong>调用方必须先确认他的会话没有在跑</strong>，而且**必须赶在会话行被删之前
     * 调它** —— 它靠 {@code session} 表定位，会话行没了它一条也匹配不上，而且不报错。
     * 见应用层的 {@code ProjectDeparture}。
     */
    void byProjectAndOwner(ProjectId projectId, UserId ownerId);
}
