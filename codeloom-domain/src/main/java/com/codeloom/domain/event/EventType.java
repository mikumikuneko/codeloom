package com.codeloom.domain.event;

/**
 * 写入 {@code event.type} 列的值，同时也是 SSE 帧里的判别字段。
 *
 * <p>这是**持久化格式的一部分**，而 {@link Event} 的 sealed 层级是编译期的东西 ——
 * 两套编号必须一一对应。名字一旦发布就不能改（历史数据里存的是字符串），
 * 所以有意用显式枚举而不是 {@code getClass().getSimpleName()} 推导。
 *
 * <p>{@link #ASSISTANT_DELTA} 和 {@link #REASONING_DELTA} 是仅有的两个**不落库**的类型 ——
 * 逐 token 落库会让 event 表每轮膨胀几千行。它们只走实时通道，投递保证见
 * {@link EphemeralEvent}。
 */
public enum EventType {

    /** 会话开起来、工作区就位。事件流的第 0 条 —— 有它，「回放一条会话」才有起点。**不进上下文**。 */
    SESSION_STARTED,

    /**
     * 状态机推进（从 {@code from} 到 {@code to}）。
     *
     * <p>**不进上下文** —— 它回答的是"这个会话当时是怎么一步步走到 FAILED 的"，
     * 那是回放与排障要看的事，模型不需要知道。
     */
    SESSION_STATE_CHANGED,

    /** 用户发给 agent 的话。**一轮就是从这里开始的** —— 回滚界面上列的每一行，背后都是一条它。 */
    USER_MESSAGE,

    /**
     * 从**别的会话**送来的留言。和 {@link #USER_MESSAGE} 分开是必须的 ——
     * 投影出来都是 user 角色，但"这话是谁说的"决定了模型该不该照做。
     */
    AGENT_NOTE_DELIVERED,

    /**
     * 平台注入的指令（如"自动验证失败，请修正"）。
     *
     * <p>和 {@link #USER_MESSAGE} 分开是必须的：混用会让审计流里分不清
     * "用户说的"和"平台说的"，而回滚正是按 turn 对齐代码与对话的。
     */
    PLATFORM_INSTRUCTION,

    /** 正文的流式增量。不落库，见类注释。 */
    ASSISTANT_DELTA,

    /**
     * 思考过程的流式增量。不落库，见类注释。
     *
     * <p>和 {@link #ASSISTANT_DELTA} 分开是必须的：界面上它们是两个区域（正文 / 思考），
     * 合成一个类型再靠负载里的标志位区分，前端就得先解包才知道往哪儿放。
     */
    REASONING_DELTA,

    /** 一轮完整回复。落库的是这个，不是上面两个。 */
    ASSISTANT_MESSAGE,

    /**
     * 模型请求调用一个工具。
     *
     * <p>**「模型想借工具做点什么」这件事由它表达** —— 所以下面那条审批不进上下文：
     * 两条都进的话，模型会以为有两回事。
     */
    TOOL_CALL_REQUESTED,

    /** 工具跑完了（无论成败），作为上面那次调用的答复回灌给模型。 */
    TOOL_RESULT,

    /**
     * 清掉若干旧工具结果的正文。**不进上下文** —— 它改的是"那些结果长什么样"
     * （投影时体现），不是"现在发生了什么"。
     */
    TOOL_RESULTS_CLEARED,

    /**
     * 用户把正在跑的工具掐了。
     *
     * <p>**进上下文**，替那次调用作答 —— 模型在等一个答复，"被用户取消了"就是答复本身。
     */
    TOOL_CANCELLED,

    /**
     * 进程重启后发现某次调用执行到一半就没了（崩溃恢复时补写）。
     *
     * <p>**必须进上下文**：它存在的意义正是防止重放 —— 让模型知道"那一步没跑完，
     * 先确认现场"，而不是让恢复逻辑把它整个重跑一遍（那可能造成二次修改）。
     */
    TOOL_INTERRUPTED,

    /** 某次调用需要用户来批。**只走审计，不进上下文** —— 模型请求它这件事由 TOOL_CALL_REQUESTED 表达。 */
    TOOL_APPROVAL_REQUESTED,

    /** 那次挂起的调用有了答复。**进上下文**，充当它的 tool 结果（配对靠它）。 */
    TOOL_APPROVAL_RESOLVED,

    /**
     * 那次挂起的调用被**拒绝**了：它没执行，也不会再有结果。
     *
     * <p>它和 {@link #TOOL_APPROVAL_RESOLVED} 是两个事实（决定 vs 收尾），见
     * {@code ToolRejected}。这条**不进上下文** —— 模型要听的那句话（"用户拒绝了…
     * 停下等指示"）由上面那条答复表达，这里再进一条只会让它以为有两回事。
     *
     * <p>它的用处全在**消费端**：判"这次调用结束了没有"靠的就是有没有一条收尾记录。
     */
    TOOL_REJECTED,

    /**
     * 打了一个 checkpoint：每一轮结束时一条，建会话时也有一条（第 0 轮之前那个位置）。
     *
     * <p>**不进上下文**，但回滚全靠它定位 —— 投影到它那里为止有多少条消息，
     * 是它当时记下的那个下标；回滚按它的**事件序号**去查那个下标（见
     * {@link SessionRewound#toCheckpointSeq()}），不是 {@code commitSha} ——
     * 一轮什么都没改时，那个 sha 和上一个 HEAD 是同一个。
     */
    CHECKPOINT_CREATED,

    /**
     * 这一轮改了哪些文件、各增删多少行。**在写的时候算一次**，之后它不再依赖 git。
     *
     * <p>**不进上下文** —— 模型不需要知道"我刚才改了哪几个文件"，而它每轮都有，
     * 进去会让前缀缓存每轮失效。为什么不在读的时候算，见 {@code WorkspaceChanges}。
     */
    WORKSPACE_CHANGES,

    /**
     * 一次模型调用失败了，我们决定等一下再试。
     *
     * <p>**不进上下文**，而且必须不进：它是"我们这边在重试"这件事，
     * 模型知道了只会以为自己该说点什么。而它每重试一次就多一条 ——
     * 进去还会让前缀缓存失效。
     *
     * <p>那它给谁看？**给人看** —— 重试期间界面上若空着，看的人只会觉得"卡住了"。
     * 见 {@code LlmRetryScheduled}。
     */
    LLM_RETRY_SCHEDULED,

    /**
     * 把主干同步进了会话的工作区（合并的**反方向**）。
     *
     * <p>它进上下文吗？**不进** —— 模型需要知道的是"代码变了"，而那件事它读文件就看得见。
     */
    SESSION_SYNCED,

    /**
     * 会话被回滚到某个 checkpoint。
     *
     * <p>它**进上下文的方式是"删"**：按自己的 {@code toCheckpointSeq} 找回那个下标，
     * 把后面的对话整段截掉。所以它自己不产出任何一条消息。
     */
    SESSION_REWOUND,

    /**
     * 一次改动验证的结论（{@code mvn test} 跑没跑过之类）。
     *
     * <p>**不进上下文** —— 它是派生的：证据在那次调用的 {@link #TOOL_RESULT} 里，
     * 而"失败要重试"是平台的决定，走 {@link #PLATFORM_INSTRUCTION} 告诉模型。
     */
    VERIFICATION_RESULT,

    /**
     * 一次上下文压缩。它**改的是投影**（从某个序号起不再送给模型），
     * 不是删事件 —— 详见 {@code ContextCompacted}。
     */
    CONTEXT_COMPACTED,

    /**
     * 任务清单被写了一遍（整份替换）。
     *
     * <p>它**进上下文的方式是"重新注入"**：投影时把**最后一份**清单追加在消息末尾
     *（不是每条清单都留在历史里）—— 于是压缩把前面的对话浓缩掉之后，清单仍然在
     * 模型眼前。压缩的水位线**不适用于它**，回滚的水位线适用 —— 两个理由都写在
     * {@code ContextAssembler} 里。
     */
    TODO_LIST_UPDATED,

    /**
     * 会话换了模型。**不进上下文** —— 模型自己不需要知道"我被换掉了"，
     * 它写的每条消息上已经带着模型名了（见 {@code AssistantMessage}）。
     */
    MODEL_CHANGED,

    /** 一轮的用量结算。**不进上下文** —— 它每轮都出现，进去会让前缀缓存彻底失效。 */
    TURN_TOKENS_USED,
}
