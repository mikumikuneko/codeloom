package com.codeloom.agent.loop;

/**
 * **provider 说"这次装不下"之后，修一下持久状态。**
 *
 * <h2>为什么需要它</h2>
 * 阈值压缩是**预防**，它是**兜底**。两者都要有，因为阈值那一侧靠的是"我们估的上下文
 * 有多少 token"，而那个估算器是会错的 —— 我们就把窗口常量写错过（估得偏大，
 * 压缩在远未满时就触发了）。估算错的方向反过来（估小了）时，
 * 表现就是 provider 直接拒绝：**没有这条兜底，那一轮就只是失败。**
 *
 * <h2>为什么是"修一下"，不是"重发一次"</h2>
 * 同样这个请求重发一万次都是同样的拒绝（{@code LlmCallException#retryable()} 对它是 false）。
 * 有意义的重试必须是**换了状态之后**的：先把模型可见的上下文压小，再发。
 *
 * <p>两个参考实现在这一处的形状是一样的，而且两家都把它放在**循环内**：
 * Claude Code 在流式循环里直接重发那一轮，并把"为什么重来"记进这一步的状态里；
 * deepseek-harness 让一个监听者修好持久状态、回一句"可以重试"，由循环**从持久日志**
 * 重开一次请求（所以已经跑过的工具不会重跑）。
 *
 * <h2>返回值是"修动了吗"，不是"成功了吗"</h2>
 * 这条规矩是从两个参考实现那儿学来的，而且是它们写得最硬的一条：**只有模型可见的状态
 * 真的变了，才允许重试**。两家各自留了一个证据 —— deepseek-harness 拿"模型看到的那份
 * 内容换过几代"的前后比较当证据，Claude Code 记一个"这条补救路走过没有"的标记。
 * 理由写在它们的注释里：一个自定义的后端完全可能"报告成功"却没改任何模型可见的东西，
 * 那时重试就是纯粹多烧一次调用。
 *
 * <p>我们的对应物很直接：**压缩真的落了一条事件吗**（{@code ContextCompacted}）。
 * 落了才算修动。
 */
@FunctionalInterface
public interface ContextRepair {

    /**
     * 上下文装不下了 —— 修一下（压缩），然后由循环重发。
     *
     * <p>这个方法**会写事件流**（压缩就是落一条 {@code ContextCompacted}），
     * 所以实现它的那一层必须有存储 —— 循环自己是没有的，这也是它被做成注入的原因。
     *
     * @return 模型可见的状态**真的变了**吗。false 会让循环把**原始那个错误**抛出去，
     *         而不是编一个"压缩失败" —— 修不动的时候，provider 那句话才是真相
     */
    boolean afterContextOverflow();
}
