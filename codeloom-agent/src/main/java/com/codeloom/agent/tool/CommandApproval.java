package com.codeloom.agent.tool;

import java.util.Optional;

/**
 * 「这一行命令要不要先问人」—— 收整行命令，回来的是**理由**。
 *
 * <h2>为什么不是 {@code Predicate<String>}</h2>
 * 返回一个布尔的话，**人点"批准"的时候界面上只有一句"等你批准一次调用"，不说为什么**。
 * 而那三种情况下要人过目的东西完全不同 —— 一个不认识程序、一个动的是工作区外面的路径、
 * 一个是这行命令压根看不懂 —— 让人在不知道是哪一种的情况下点"同意"，这个确认就是走过场。
 *
 * <p>反过来看就更明显：**人为什么拒绝，我们是记的**（{@code ToolApprovalResolved.reason}）；
 * 而**我们为什么问，一个字都没记**。同一个决定的两半，只留了一半。
 *
 * <p>两个参考实现在这一处的形状都是"**带理由的决定**"，不是一个布尔：
 * Claude Code 的权限判定返回的是一个决定对象；deepseek-harness 的权限守卫返回一个理由，
 * 而且**它的返回类型里故意没有"允许"** —— 返回的理由只能收紧权限，
 * 后面的监听者没法把它撤销回去。
 *
 * <h2>为什么"没有理由"就等于"不用问"</h2>
 * 因为我们这几种情况每一种都说得清为什么。真出现一种"要问但说不出为什么"的情况，
 * 那说明判据本身没想清楚 —— 这时候逼着写判据的人编一句理由，比放行更值得。
 */
@FunctionalInterface
public interface CommandApproval {

    /**
     * @param commandLine 模型写的那一行命令。**可能是 null** —— 有些调用没有命令参数
     *                    （别的工具不走这条判据），null 表示"这次没有命令"，
     *                    不是"一条需要审批的命令"
     * @return 空 = 不用问，直接跑；有值 = 要问人，**而这就是为什么要问**
     */
    Optional<String> reasonToAsk(String commandLine);
}
