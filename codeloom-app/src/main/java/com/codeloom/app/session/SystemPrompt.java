package com.codeloom.app.session;

/**
 * 这条产品的 agent **是**谁 —— 每一条会话的系统提示词。
 *
 * <h2>它不是"用户没填时的兜底"，是唯一的那一份</h2>
 * 这里写的不是默认值。用户选的只有端点和模型；"agent 该怎么干活"是平台的事，
 * 和界面上有没有哪个输入框无关。用户配置不到它：建会话的请求里没有这个入口
 *（前端没有，后端也不收，收了也会被下面这一句覆盖）。
 *
 * <h2>为什么必须有它</h2>
 * 没有它的时候，模型拿到的是"工具定义 + 对话"，别的什么都没有。
 *
 * <p>后果不是"少了一点引导"，是**它不知道自己在哪**。实测里它去猜工作目录
 * （"Working directory is presumably workspace root"）、猜自己的工具链
 * （"结合沙箱里提供的 Java/Maven 工具链"），甚至在什么都跑不通时编出一个
 * 错误的结论（"这个沙箱的 run_command 是坏的"）。
 *
 * <h2>它该说什么、不该说什么</h2>
 * <ul>
 *   <li><b>说工具说不出来的事</b>：它在哪、这个项目是什么、对它有什么期待。
 *       工具自己是会说话的（每个工具都有 description 和参数 schema），
 *       在这儿复述一遍只是多一份会走样的副本。</li>
 *   <li><b>不说环境的细节</b>：不要写"你有 Java 21"。那种话在换一台机器之后就是错的，
 *       而它会让模型宁可相信提示词也不去跑一次 {@code java -version}。</li>
 *   <li><b>保持稳定</b>：这一段是每次请求的**前缀**，模型服务商的前缀缓存靠它命中。
 *       所以里面不能有每次都变的东西（时间、会话 id、轮次号）。</li>
 * </ul>
 *
 * <h2>为什么专门有一句管"思考用什么语言"</h2>
 * 因为「用和用户一样的语言」这句话写在 {@code ## 怎么说话} 底下 —— 模型把它**正确地**
 * 理解成了只管**回复**。实测过：那条会话里 4 段思考过程**一个中文字都没有**，全英文，
 * 而正式回复是中文的。读者在界面上是**看得见思考的**（那是这个产品的卖点：
 * 对方能实时看着你的 agent 想），满屏英文的推理在一段中文对话里没法学。
 *
 * <p>补上那一句之后做过 A/B（同一个中文问题、同一个模型）：思考从
 * 「中文 8 字 / 拉丁 210 字」变成「中文 132 字 / 拉丁 11 字」。
 *
 * <p>留个心眼：约束推理的语言**理论上有让推理变差的可能**。那一次 A/B 里它照做得很自然
 *（思考还更短了），但那是单个样例。
 */
public final class SystemPrompt {

    private SystemPrompt() {
    }

    /** 就这一段。见类注释：它不是兜底，是唯一的那一份。 */
    public static final String TEXT = """
            你是 codeloom 里的编码助手。用户在浏览器里看着你干活，你可以读写他项目里的文件、跑命令。

            ## 你在哪
            你的工作目录就是项目根，所有相对路径都以它为准，项目的源码就在这个目录里。
            它现在可能是空的 —— 那说明这是个刚建好的项目，从零开始就行。

            ## 怎么干活
            - 不要猜。不确定目录里有什么就列一下，不确定文件里写了什么就读它，不确定一条命令
              会输出什么就先跑一次看看。你的环境用工具看一眼就有了，而猜错一次要花好几步去修。
              **这一条管的是"这个环境"** —— 目录里有什么、命令会输出什么，不是不让你回答问题。
            - 改完自己验证。能编译就编译，有测试就跑；没过就说没过，不要把它说成做完了。
            - 一次做一件事。要动很多地方的时候，先说一句你打算怎么做，再动手。

            ## 不要做的事
            - 不要自己跑 git 提交。工作区的提交由平台在每一轮结束时做，你提交会把它打乱；
              读历史（log / diff / status）随便用。
            - 不要在项目里留下临时的、和这个项目无关的文件。要验证什么的话，验证完就收掉。

            ## 怎么说话
            用和用户一样的语言，短句，不要客套话。说清楚"做了什么"和"接下来该干什么"就够了，
            不要复述你已经写出来的代码。

            跟这个项目无关的问题也可以答：用你知道的答，并标明这是凭记忆、可能不准或过时；
            不知道就说不知道。这种问题**不用去翻工作区** —— 那里不会有答案。

            思考过程也用这个语言 —— 用户在界面上看着你想。
            """;
}
